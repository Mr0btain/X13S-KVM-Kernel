#!/bin/sh
# Write /boot/grub/el2.cfg for grubel2.efi (EL2 / KVM boot entry).
# Replaces AndroidEmulator/scripts/el2-grubcfg.sh; installed as
# /etc/kernel/postinst.d/zz-el2-grubcfg by scripts/install-kernel.sh.
#
# Entry 1: newest *-el2 kernel (patched, DSP attach) + X13s -el2 dtb with
#          dts/x13s-el2-dsp.dtso applied (qcom,broken-reset on the DSPs)
#          and the cluster idle state removed (suspend at EL2).
# Entry 2: newest stock -generic kernel at EL2 (old behaviour: KVM, no DSPs).
set -eu

OUT=${EL2_GRUBCFG:-/boot/grub/el2.cfg}
KDIR=${EL2_KDIR:-/boot/el2}
DTBO=${EL2_DTBO:-/usr/local/share/kernel-work/x13s-el2-dsp.dtbo}
DTBNAME=sc8280xp-lenovo-thinkpad-x13s-el2.dtb

GRUB_CMDLINE_LINUX="" GRUB_CMDLINE_LINUX_DEFAULT=""
. /etc/default/grub
for f in /etc/default/grub.d/*.cfg; do [ -e "$f" ] && . "$f"; done
# Keep boot messages visible: "quiet splash" hides why an EL2 boot stops.
args=$(echo "$GRUB_CMDLINE_LINUX $GRUB_CMDLINE_LINUX_DEFAULT" | sed 's/\bquiet\b//; s/\bsplash\b//')

# dtb location: Ubuntu packages -> /lib/firmware/<ver>/device-tree/qcom,
# kernel.org bindeb-pkg -> /usr/lib/linux-image-<ver>/qcom.
dtb_for() {
	for d in "/lib/firmware/$1/device-tree/qcom" "/usr/lib/linux-image-$1/qcom"; do
		[ -e "$d/$DTBNAME" ] && { echo "$d/$DTBNAME"; return; }
	done
}
newest() {
	linux-version list | grep -E -e "$1" | linux-version sort --reverse | while read -r v; do
		[ -e "/boot/vmlinuz-$v" ] && [ -n "$(dtb_for "$v")" ] && { echo "$v"; break; }
	done
}

el2ver=$(newest -el2\$ || true)
genver=$(newest -generic\$ || true)
uuid=$(findmnt -no UUID /)
mkdir -p "$KDIR"

# Patched kernel: install-time dtb = packaged -el2 dtb + our overlay.
if [ -n "$el2ver" ]; then
	if [ -e "$DTBO" ]; then
		fdtoverlay -i "$(dtb_for "$el2ver")" -o "$KDIR/$el2ver.dtb" "$DTBO"
	else
		echo "el2-grubcfg: missing $DTBO; DSPs won't attach" >&2
		cp "$(dtb_for "$el2ver")" "$KDIR/$el2ver.dtb"
	fi
	# No cluster power collapse (cluster-sleep-0, PSCI 0x4100c344): at EL2 the
	# s2idle entry into it hard-resets the machine (notes/boot-log.md).
	# Per-core sleep (cpu-sleep-0-0) stays.
	fdtput -d "$KDIR/$el2ver.dtb" /psci/power-domain-cpu-cluster0 domain-idle-states
	rm -f "$KDIR/$el2ver-nocluster.dtb"
fi

# Stock Ubuntu vmlinuz is a stubble (systemd-stub) PE that swaps in its own
# dtb; boot the bare kernel from its .linux section so the EL2 dtb survives.
if [ -n "$genver" ]; then
	k="$KDIR/vmlinuz-$genver"
	if [ ! -s "$k" ] || [ "/boot/vmlinuz-$genver" -nt "$k" ]; then
		objcopy -O binary --only-section=.linux "/boot/vmlinuz-$genver" "$k.new"
		if [ "$(head -c2 "$k.new")" = MZ ]; then mv "$k.new" "$k"; else rm -f "$k.new"; cp "/boot/vmlinuz-$genver" "$k"; fi
	fi
fi
# Drop files whose kernel package is gone.
for f in "$KDIR"/vmlinuz-* "$KDIR"/*.dtb; do
	[ -e "$f" ] || continue
	v=${f##*/}; v=${v#vmlinuz-}; v=${v%.dtb}; v=${v%-nocluster}
	[ -e "/boot/vmlinuz-$v" ] || rm -f "$f"
done

{
	echo "# Generated by kernel-work el2-grubcfg ($(date -I)); do not edit."
	echo "search --no-floppy --fs-uuid --set=root $uuid"
	echo "set default=0"
	echo "set timeout=3"
	if [ -n "$el2ver" ]; then cat <<EOF
menuentry 'Linux $el2ver (EL2 / KVM + DSPs)' {
	linux	/boot/vmlinuz-$el2ver root=UUID=$uuid ro $args
	initrd	/boot/initrd.img-$el2ver
	devicetree	/boot/el2/$el2ver.dtb
}
EOF
	fi
	if [ -n "$genver" ]; then cat <<EOF
menuentry 'Ubuntu $genver (EL2 / KVM, no DSPs)' {
	linux	/boot/el2/vmlinuz-$genver root=UUID=$uuid ro $args
	initrd	/boot/initrd.img-$genver
	devicetree	$(dtb_for "$genver")
}
EOF
	fi
	cat <<'EOF'
menuentry 'UEFI firmware settings' {
	fwsetup
}
EOF
} > "$OUT.new"
mv "$OUT.new" "$OUT"
echo "el2-grubcfg: $OUT -> ${el2ver:-none} / ${genver:-none}"
